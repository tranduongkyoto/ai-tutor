#!/usr/bin/env python3
"""Build a 2-option flashcard page from a deck JSON, using new-solutions-flashcards.html as the template.

Deck JSON:
  {"sections": {"A": "Topic", ...},
   "cards": [{"id": "A1", "q": 7, "ans": "B", "scenario": "...", "ok": "...", "bad": "...", "why": "..."}, ...]}

Usage:
  python3 aws-sap/build_flashcards.py --deck deck.json --out aws-sap/td1-flashcards.html \
      --title "TD1 Flashcards" --subtitle "TD Set 1 · all 75 questions" --source "TD1" \
      --store sap-td1-flashcards-rounds --repeat 2,3,7 [--export practice-exam/sap/td1_retake_export.md]

--export: if given, every card's "ans" is checked against the export's correct answer (fails fast on mismatch).
"""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / "new-solutions-flashcards.html"


def check_against_export(cards, export_path):
    """Fail if a card's answer letters differ from the test export (guards against wrong 'ok' sides)."""
    text = Path(export_path).read_text(encoding="utf-8")
    answers = {int(n): a.strip() for n, a in re.findall(
        r"^## Câu (\d+) — .*?> \*\*Đáp án đúng:\*\* ([A-G, ]+)", text, re.M | re.S)}
    bad = [c["id"] for c in cards if answers.get(c["q"]) != c["ans"].strip()]
    missing = sorted(set(answers) - {c["q"] for c in cards})
    if bad or missing:
        raise SystemExit(f"answer check failed: mismatched {bad}, missing questions {missing}")


def build(args):
    deck = json.loads(Path(args.deck).read_text(encoding="utf-8"))
    cards, sections = deck["cards"], deck["sections"]
    if args.export:
        check_against_export(cards, args.export)
    repeat = {int(x) for x in args.repeat.split(",") if x.strip()}
    rows = [[c["id"], c["scenario"], c["ok"], c["bad"], c["why"], f'{args.source} Q{c["q"]}', int(c["q"] in repeat)]
            for c in cards]
    page = TEMPLATE.read_text(encoding="utf-8")
    cards_js = "const CARDS = [\n" + ",\n".join(" " + json.dumps(r, ensure_ascii=False) for r in rows) + ",\n].map("
    page = re.sub(r"const CARDS = \[\n.*?\n\]\.map\(", lambda _: cards_js, page, count=1, flags=re.S)
    page = re.sub(r"const SECTIONS = \{.*?\};", lambda _: "const SECTIONS = " + json.dumps(sections, ensure_ascii=False) + ";",
                  page, count=1, flags=re.S)
    replacements = {
        '"sap-ns-flashcards-rounds"': json.dumps(args.store),
        "<title>SAP-C02 Flashcards — Design for New Solutions</title>": f"<title>{args.title}</title>",
        "SAP-C02 Flashcards<small>Domain 2 · Design for New Solutions</small>": f"{args.title}<small>{args.subtitle}</small>",
        "secs.length === 9": f"secs.length === {len(sections)}",
        "<code>new-solutions-flashcards.md</code>": "<code>aws-sap/study-progress.md</code>",
        " * Card data — mirrors aws-sap/new-solutions-flashcards.md.": f" * Card data — generated by build_flashcards.py from {Path(args.deck).name}.",
    }
    for old, new in replacements.items():
        if old not in page:
            raise SystemExit(f"template changed, marker not found: {old}")
        page = page.replace(old, new)
    Path(args.out).write_text(page, encoding="utf-8")
    print(f"wrote {args.out}: {len(cards)} cards, {len(sections)} sections, {sum(r[6] for r in rows)} 🔁")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for name in ("deck", "out", "title", "subtitle", "source", "store"):
        ap.add_argument(f"--{name}", required=True)
    ap.add_argument("--repeat", default="", help="comma-separated question numbers to mark 🔁")
    ap.add_argument("--export", help="test export to verify answers against")
    build(ap.parse_args())
